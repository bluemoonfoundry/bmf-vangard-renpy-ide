#!/usr/bin/env node
/**
 * Records and verifies where the committed WASM grammars came from.
 *
 * `renpy.wasm` is a build artifact of `grammar.js` + `src/scanner.c`, but it
 * is committed because building it needs emscripten (or Docker) and the app
 * must not require either to run or test. `wasm-provenance.json` ties the
 * binary back to its sources: it records the SHA-256 of every build input and
 * of the output. If someone edits the grammar without rebuilding — or commits
 * a binary that wasn't built from the committed sources — the hashes stop
 * matching and `npm run check` (and the app's `npm test`) fails.
 *
 * Usage:
 *   node scripts/provenance.mjs write   # after `npm run build`
 *   node scripts/provenance.mjs check   # exits 1 on any mismatch
 *
 * Text inputs are hashed with CRLF normalized to LF so the result is the same
 * on every platform regardless of checkout line-ending settings.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(ROOT, '..');
const MANIFEST = join(ROOT, 'wasm-provenance.json');

/** Hand-written sources: what a human edits. */
const SOURCE_INPUTS = ['grammar.js', 'src/scanner.c'];
/** Generated by `tree-sitter generate` from grammar.js; compiled into the wasm. */
const GENERATED_INPUTS = [
  'src/parser.c',
  'src/tree_sitter/parser.h',
  'src/tree_sitter/array.h',
  'src/tree_sitter/alloc.h',
];

function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

function hashText(rel) {
  return sha256(readFileSync(join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n'));
}

function hashBinary(absPath) {
  return sha256(readFileSync(absPath));
}

function cliVersion() {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'node_modules/tree-sitter-cli/package.json'), 'utf8'));
  return pkg.version;
}

function current() {
  const inputs = {};
  for (const rel of [...SOURCE_INPUTS, ...GENERATED_INPUTS]) inputs[rel] = hashText(rel);
  return { inputs, output: hashBinary(join(ROOT, 'renpy.wasm')) };
}

function write() {
  const existing = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const { inputs, output } = current();
  existing.renpy = {
    ...existing.renpy,
    treeSitterCli: cliVersion(),
    inputs,
    sha256: output,
  };
  writeFileSync(MANIFEST, `${JSON.stringify(existing, null, 2)}\n`);
  console.log(`wrote ${MANIFEST}`);
}

function check() {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const { inputs, output } = current();
  const problems = [];
  for (const [rel, hash] of Object.entries(inputs)) {
    if (manifest.renpy.inputs[rel] !== hash) problems.push(`${rel} changed since renpy.wasm was built`);
  }
  if (manifest.renpy.sha256 !== output) problems.push('renpy.wasm does not match the recorded build output');
  for (const [rel, entry] of Object.entries(manifest.vendored ?? {})) {
    if (hashBinary(join(REPO, rel)) !== entry.sha256) problems.push(`${rel} does not match its recorded upstream hash`);
  }
  if (problems.length) {
    console.error('Grammar provenance check failed:\n  - ' + problems.join('\n  - '));
    console.error('Rebuild with `npm run build:grammar` from the repo root (requires Docker or emscripten).');
    process.exit(1);
  }
  console.log('Grammar provenance OK');
}

const mode = process.argv[2];
if (mode === 'write') write();
else if (mode === 'check') check();
else {
  console.error('usage: provenance.mjs <write|check>');
  process.exit(2);
}
